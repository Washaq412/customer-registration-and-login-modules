CREATE DATABASE IF NOT EXISTS marketplace_db;
USE marketplace_db;

CREATE TABLE users (
  user_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(50) NOT NULL,
  mobile_number VARCHAR(10) NOT NULL UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  account_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  mobile_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CHECK (account_status IN ('PENDING', 'ACTIVE', 'BLOCKED'))
);

CREATE TABLE otp_verifications (
  otp_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  otp_hash VARCHAR(255) NOT NULL,
  purpose VARCHAR(30) NOT NULL DEFAULT 'REGISTRATION',
  expires_at DATETIME NOT NULL,
  attempts_used INT NOT NULL DEFAULT 0,
  max_attempts INT NOT NULL DEFAULT 3,
  resend_count INT NOT NULL DEFAULT 0,
  verified_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(user_id),
  CHECK (attempts_used >= 0),
  CHECK (max_attempts > 0)
);

CREATE TABLE user_consents (
  consent_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  terms_version VARCHAR(20) NOT NULL,
  accepted BOOLEAN NOT NULL DEFAULT FALSE,
  accepted_at DATETIME NULL,
  FOREIGN KEY (user_id) REFERENCES users(user_id)
);

CREATE TABLE registration_drafts (
  draft_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  session_token_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(50) NULL,
  mobile_number VARCHAR(10) NULL,
  email VARCHAR(254) NULL,
  terms_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  draft_status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
  expires_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CHECK (draft_status IN ('IN_PROGRESS', 'COMPLETED'))
);

CREATE TABLE registration_attempts (
  attempt_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NULL,
  attempt_type VARCHAR(30) NOT NULL,
  success BOOLEAN NOT NULL DEFAULT FALSE,
  failure_reason VARCHAR(100) NULL,
  attempted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(user_id)
);